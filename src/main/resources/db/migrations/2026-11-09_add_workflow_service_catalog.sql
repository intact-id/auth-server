-- Workflow service catalog: the services workflows are built from. code matches billing-service's
-- service charge codes. Seeds the services that exist today; safe to run more than once.
CREATE TABLE IF NOT EXISTS workflow_service
(
    id              VARCHAR(255) NOT NULL PRIMARY KEY,
    created_at      TIMESTAMP(6),
    updated_at      TIMESTAMP(6),
    created_by      VARCHAR(255),
    updated_by      VARCHAR(255),
    code            VARCHAR(100) NOT NULL UNIQUE,
    name            VARCHAR(255) NOT NULL,
    description     TEXT,
    category        VARCHAR(50)  NOT NULL,
    status          VARCHAR(30)  NOT NULL,
    subject_types   JSONB        NOT NULL DEFAULT '[]',
    countries       JSONB        NOT NULL DEFAULT '[]',
    requires        JSONB        NOT NULL DEFAULT '[]',
    required_fields JSONB        NOT NULL DEFAULT '[]',
    captures        JSONB        NOT NULL DEFAULT '[]',
    outputs         JSONB        NOT NULL DEFAULT '[]',
    ui              JSONB        NOT NULL DEFAULT '{}',
    settings_schema JSONB        NOT NULL DEFAULT '{}',
    sort_order      INTEGER      NOT NULL DEFAULT 0
);

